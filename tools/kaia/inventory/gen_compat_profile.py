#!/usr/bin/env python3
"""Writes the Kaia compatibility profile, frontend/kaia/compat_profile.lua.

Run from the repository root:

    python3 -I tools/kaia/inventory/gen_compat_profile.py

The bundled plugin names come from docs/kaia/inventory/plugins.json. Each
plugin's class and platform come from tools/kaia/inventory/curation.json, the
file that plugin_inventory.py uses for plugins.md. Kaia's own plugins are
listed by hand in KAIA_PLUGINS.

Every entry has tested = false until a device test workflow passes for it.
The output is sorted and has no timestamps, so a rerun produces no diff.

Standard library only.
"""

import argparse
import json
import os
import sys

BASELINE = "KOReader v2026.07.1"
PROFILE_VERSION = 1

CLASSES = (
    "Applicable bundled plugin",
    "Plugin using shared widgets",
    "Custom-drawing or deeply coupled",
    "Not applicable on Kobo",
    "Kaia",
)
PLATFORMS = ("applicable", "not applicable", "debug only")

# Plugins that ship with Kaia and are not in the upstream inventory.
KAIA_PLUGINS = {
    "kaiastickers": "applicable",
    "kaiaexample": "applicable",
}
KAIA_CLASS = "Kaia"

OUTPUT = "frontend/kaia/compat_profile.lua"


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load_json(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def collect_entries(root):
    """Returns {name: (class, platform)} for every profile entry, or raises ValueError."""
    inventory = load_json(os.path.join(root, "docs", "kaia", "inventory", "plugins.json"))
    curation = load_json(os.path.join(root, "tools", "kaia", "inventory", "curation.json"))

    names = {plugin["name"] for plugin in inventory["plugins"]}
    curated = curation["plugins"]

    errors = []
    for name in sorted(names - set(curated)):
        errors.append("no curation entry for bundled plugin %s" % name)
    for name in sorted(set(curated) - names):
        errors.append("curation entry %s has no bundled plugin" % name)
    for name in sorted(names & set(curated)):
        entry = curated[name]
        if entry.get("class") not in CLASSES:
            errors.append("%s: unknown class %r" % (name, entry.get("class")))
        if entry.get("platform") not in PLATFORMS:
            errors.append("%s: unknown platform %r" % (name, entry.get("platform")))
    for name in sorted(KAIA_PLUGINS):
        if name in names or name in curated:
            errors.append("%s is a Kaia plugin but also appears in the upstream inventory" % name)
    if errors:
        raise ValueError("; ".join(errors))

    entries = {}
    for name in names:
        entries[name] = (curated[name]["class"], curated[name]["platform"])
    for name, platform in KAIA_PLUGINS.items():
        entries[name] = (KAIA_CLASS, platform)
    return entries


def render(entries):
    lines = [
        "-- Generated by tools/kaia/inventory/gen_compat_profile.py. Do not edit by hand.",
        "--",
        "-- Compatibility class and platform for each plugin. `tested` is true only",
        "-- after the plugin passed its device workflow on the baseline below.",
        "--",
        "-- @module kaia.compat_profile",
        "",
        "return {",
        "    version = %d," % PROFILE_VERSION,
        "    baseline = %s," % lua_string(BASELINE),
        "    plugins = {",
    ]
    for name in sorted(entries):
        plugin_class, platform = entries[name]
        lines.append(
            "        [%s] = { class = %s, platform = %s, tested = false },"
            % (lua_string(name), lua_string(plugin_class), lua_string(platform))
        )
    lines.append("    },")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv):
    default_root = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--root", default=default_root, help="repository root (default: the checkout this script is in)")
    parser.add_argument("--out", default=OUTPUT, help="output path, relative to the root")
    args = parser.parse_args(argv)

    root = os.path.abspath(args.root)
    try:
        entries = collect_entries(root)
    except ValueError as err:
        print("error: %s" % err, file=sys.stderr)
        return 1

    text = render(entries)
    if any(ch in text for ch in (chr(0x2014), chr(0x2013))):
        print("error: generated text contains an em or en dash", file=sys.stderr)
        return 1

    out_path = args.out if os.path.isabs(args.out) else os.path.join(root, args.out)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s (%d plugins)" % (out_path, len(entries)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
